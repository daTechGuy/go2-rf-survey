"""Gazebo Go2 (CHAMP, Velodyne) for our tests: go2_config's gazebo_velodyne
launch, with one change -- CHAMP's controller listens on /sim/cmd_vel, not
/cmd_vel. /cmd_vel is our loop -> bridge link; the sim robot must only move
through the bridge's sport requests (via sim/go2_sim_adapter), as the real
one does. The patched bringup is generated by sim/run_sim.sh.

    ros2 launch sim/launch/go2_sim.launch.py world:=<path> gui:=false bringup:=<patched>
"""

import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration


def generate_launch_description():
    cfg = get_package_share_directory("go2_config")
    desc = get_package_share_directory("go2_description")
    L = LaunchConfiguration
    args = [
        DeclareLaunchArgument("world", default_value=os.path.join(cfg, "worlds/default.world")),
        DeclareLaunchArgument("gui", default_value="false"),
        DeclareLaunchArgument("bringup", description="patched champ bringup.launch.py"),
        DeclareLaunchArgument("description",
                              default_value=os.path.join(desc, "xacro/robot_VLP.xacro")),
    ]
    bringup = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(L("bringup")),
        launch_arguments={
            "description_path": L("description"),
            "joints_map_path": os.path.join(cfg, "config/joints/joints.yaml"),
            "links_map_path": os.path.join(cfg, "config/links/links.yaml"),
            "gait_config_path": os.path.join(cfg, "config/gait/gait.yaml"),
            "use_sim_time": "true", "robot_name": "go2", "gazebo": "true",
            "lite": "false", "rviz": "false",
            "joint_controller_topic": "joint_group_effort_controller/joint_trajectory",
            "hardware_connected": "false", "publish_foot_contacts": "false",
            "close_loop_odom": "true",
        }.items(),
    )
    gazebo = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(os.path.join(
            get_package_share_directory("champ_gazebo"), "launch", "gazebo.launch.py")),
        launch_arguments={
            "use_sim_time": "true", "robot_name": "go2", "world": L("world"),
            "lite": "false", "gui": L("gui"), "close_loop_odom": "true",
            # spawn at the origin facing +x: the tape on the floor
            "world_init_x": "0.0", "world_init_y": "0.0", "world_init_z": "0.275",
            "world_init_heading": "0.0",
        }.items(),
    )
    return LaunchDescription(args + [bringup, gazebo])
