#!/usr/bin/env python3
"""Generate Gazebo Classic worlds for the Go2 tests. Stdlib only.

    python3 sim/worlds/make_worlds.py                    # writes small_room + classroom
    python3 sim/worlds/make_worlds.py --aisle 1.0        # a tighter classroom aisle

small_room.world  -- field guide 01: 3 x 2.5 m clear room, robot at the
                     origin facing +x, a knee-high box you can enable for
                     the obstacle-stop test (--box).
classroom.world   -- field guide 02: the robot starts in the doorway at the
                     origin facing +x (down the aisle); desks line the aisle
                     for its first ``--aisle-length`` metres; open floor at
                     the far end to turn round. Placeholder sizes until the
                     real room is measured -- every one is a flag.

Coordinates: x forward from the start, y to the left, metres. Gazebo spawns
the robot at the origin (sim/run_sim.sh), so the route geometry here
matches the real route from the tape on the floor.
"""

from __future__ import annotations

import argparse
from pathlib import Path

HEADER = """<?xml version="1.0"?>
<!-- generated by sim/worlds/make_worlds.py; edit its flags, not this file -->
<sdf version="1.6">
  <!-- {name}. The world must be called "default": the Velodyne plugin
       listens for scans under /gazebo/default/... whatever the world's name. -->
  <world name="default">
    <include><uri>model://sun</uri></include>
    <include><uri>model://ground_plane</uri></include>
    <physics type="ode"><real_time_update_rate>1000</real_time_update_rate>
      <max_step_size>0.001</max_step_size></physics>
"""
FOOTER = "  </world>\n</sdf>\n"


def box(name, x, y, sx, sy, sz, rgb="0.6 0.6 0.6"):
    """Static box with its footprint centred on (x, y), sitting on the floor."""
    return f"""    <model name="{name}"><static>true</static>
      <pose>{x:.3f} {y:.3f} {sz / 2:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="c"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse></material></visual>
      </link></model>
"""


def walls(x0, x1, y0, y1, h=2.5, t=0.1, door=None):
    """Four walls around [x0,x1] x [y0,y1]. ``door`` = (y_from, y_to) gap in
    the x0 wall (the robot starts in it)."""
    out = [box("wall_far", x1 + t / 2, (y0 + y1) / 2, t, y1 - y0 + 2 * t, h),
           box("wall_left", (x0 + x1) / 2, y1 + t / 2, x1 - x0, t, h),
           box("wall_right", (x0 + x1) / 2, y0 - t / 2, x1 - x0, t, h)]
    if door is None:
        out.append(box("wall_near", x0 - t / 2, (y0 + y1) / 2, t, y1 - y0 + 2 * t, h))
    else:
        d0, d1 = door
        if d0 > y0:
            out.append(box("wall_near_r", x0 - t / 2, (y0 + d0) / 2, t, d0 - y0, h))
        if y1 > d1:
            out.append(box("wall_near_l", x0 - t / 2, (d1 + y1) / 2, t, y1 - d1, h))
    return out


def small_room(with_box: bool) -> str:
    parts = walls(-0.5, 2.5, -1.25, 1.25)
    if with_box:
        parts.append(box("box", 1.3, 0.0, 0.4, 0.4, 0.5, "0.8 0.5 0.2"))   # knee high, 1 m out
    return HEADER.format(name="small_room") + "".join(parts) + FOOTER


def classroom(aisle: float, aisle_length: float, room_len: float, room_w: float,
              desk_d: float = 0.6, desk_w: float = 1.2, desk_h: float = 0.75) -> str:
    """Desks in rows either side of the aisle (centred on y=0) for x in
    [0.3, aisle_length]; the room continues to room_len with open floor."""
    half = aisle / 2
    y0, y1 = -room_w / 2, room_w / 2
    parts = walls(-0.2, room_len, y0, y1, door=(-0.5, 0.5))
    n = 0
    x = 0.3 + desk_d / 2
    while x + desk_d / 2 <= aisle_length:
        for side in (1, -1):
            y = side * (half + desk_w / 2)
            while abs(y) + desk_w / 2 <= room_w / 2 - 0.3:
                parts.append(box(f"desk_{n}", x, y, desk_d, desk_w, desk_h, "0.55 0.4 0.25"))
                n += 1
                y += side * (desk_w + 0.05)
        x += desk_d + 0.6                              # a chair's depth between rows
    return HEADER.format(name="classroom") + "".join(parts) + FOOTER


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--aisle", type=float, default=1.2, help="clear aisle width, m")
    ap.add_argument("--aisle-length", type=float, default=3.0, help="desks along the first N m")
    ap.add_argument("--room-length", type=float, default=6.0)
    ap.add_argument("--room-width", type=float, default=7.0)
    ap.add_argument("--box", action="store_true", help="small room: add the obstacle box")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent)
    a = ap.parse_args(argv)
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "small_room.world").write_text(small_room(a.box))
    (a.out / "classroom.world").write_text(
        classroom(a.aisle, a.aisle_length, a.room_length, a.room_width))
    print(f"wrote {a.out / 'small_room.world'} (box={'yes' if a.box else 'no'}) and "
          f"{a.out / 'classroom.world'} (aisle {a.aisle} m)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
